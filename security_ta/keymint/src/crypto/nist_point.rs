/// Returns `InvalidArgument` if (x, y), big-endian coordinates, is not on the curve.
pub fn check_point(curve: NistCurve, x: &[u8], y: &[u8]) -> Result<(), kmr_common::Error> {
    let (p, b): (&[u8], &[u8]) = match curve {
        NistCurve::P224 => (&P224_P, &P224_B),
        NistCurve::P256 => (&P256_P, &P256_B),
        NistCurve::P384 => (&P384_P, &P384_B),
        NistCurve::P521 => (&P521_P, &P521_B),
    };
    let bits = (curve.coord_len() * 8) as u32;
    let to_bigint = |bytes: &[u8]| -> Result<BigInt, kmr_common::Error> {
        let mut n = BigInt::new(bits);
        n.convert_from_octet_string(bytes, 0).map_err(Error::kmerr)?;
        Ok(n)
    };
    let (p, b, x, y) = (to_bigint(p)?, to_bigint(b)?, to_bigint(x)?, to_bigint(y)?);

    // The modular operations need operands smaller than p.
    if x.compare_big_int(&p) >= 0 || y.compare_big_int(&p) >= 0 {
        return Err(km_err!(InvalidArgument, "Peer public key coordinate out of range"));
    }

    let mut three = BigInt::new(32);
    three.convert_from_s32(3);
    // (x^2 - 3) * x + b
    let rhs = BigInt::sub_mod(&BigInt::square_mod(&x, &p), &three, &p);
    let rhs = BigInt::add_mod(&BigInt::mul_mod(&rhs, &x, &p), &b, &p);
    if BigInt::square_mod(&y, &p).compare_big_int(&rhs) != 0 {
        return Err(km_err!(InvalidArgument, "Peer public key is not on the curve"));
    }
    Ok(())
}

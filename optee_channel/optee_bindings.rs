//! GlobalPlatform TEE Client API bindings for OP-TEE's libteec.
//!
//! The types, constants and functions are generated by bindgen from
//! `tee_client_api.h`. This crate adds what bindgen cannot generate.

pub use tee_client_api_bindgen::*;

pub fn param_types(p0: u32, p1: u32, p2: u32, p3: u32) -> u32 {
    (p0 & 0xF) | ((p1 & 0xF) << 4) | ((p2 & 0xF) << 8) | ((p3 & 0xF) << 12)
}

pub fn uuid_from_str(s: &str) -> Option<TEEC_UUID> {
    let parts: Vec<&str> = s.split('-').collect();
    if parts.len() != 5 || parts[3].len() != 4 || parts[4].len() != 12 {
        return None;
    }

    let mut clock_seq_and_node = [0u8; 8];
    let clock_seq_and_node_str = [parts[3], parts[4]].concat();
    for (i, byte) in clock_seq_and_node.iter_mut().enumerate() {
        *byte = u8::from_str_radix(clock_seq_and_node_str.get(i * 2..i * 2 + 2)?, 16).ok()?;
    }

    Some(TEEC_UUID {
        timeLow: u32::from_str_radix(parts[0], 16).ok()?,
        timeMid: u16::from_str_radix(parts[1], 16).ok()?,
        timeHiAndVersion: u16::from_str_radix(parts[2], 16).ok()?,
        clockSeqAndNode: clock_seq_and_node,
    })
}
